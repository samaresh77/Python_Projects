

# | Structure  | Syntax         | Ordered                     | Mutable | Duplicates          |
# | ---------- | -------------- | --------------------------- | ------- | ------------------- |
# | List       | `[]`           | Yes                         | Yes     | Yes                 |
# | Tuple      | `()`           | Yes                         | No      | Yes                 |
# | Set        | `{}`           | Not for positional indexing | Yes     | No                  |
# | Dictionary | `{key: value}` | Key-based                   | Yes     | Keys must be unique |
